#!/usr/bin/env python3
"""Regenerate src/lib/blocktoolsManifest.ts from content/blocktools (vendored from TSavo/blocktools)."""
import glob, json, os, re
C = os.path.join(os.path.dirname(__file__), "..", "content", "blocktools")

def meta(path):
    t = open(path).read()
    title = re.search(r"^# (.+)$", t, re.M).group(1).strip().replace("`", "")
    body = re.sub(r"<!--.*?-->", "", t, flags=re.S)
    paras = [p for p in re.split(r"\n\s*\n", body) if p.strip() and not p.lstrip().startswith(("#", "    ", "```", "|", ">", "-", "*", "<"))]
    paras = [p for p in paras if len(p) > 60 and not p.startswith(("Earlier", "**DANGEROUS"))] or paras
    d = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", paras[0] if paras else title)
    d = " ".join(d.replace("`", "").replace("**", "").split())
    if len(d) > 155:
        d = d[:152].rsplit(" ", 1)[0] + "…"
    return title, d

# From docs/README.md (the upstream docs index), where a page's own first paragraph is a poor summary.
OVR = {
 "getting-started": "Getting started with blocktools: install from the v0.1.1 release or from source, then your first sealed run on public test data.",
 "security": "blocktools security: threat model, sealed runs, and what is and is not protected.",
 "claims": "Every blocktools number and security claim, the command that measured it, and where it was measured.",
 "refusals": "Every blocktools status and failure code, what causes it and what to do.",
 "cookbook": "blocktools cookbook by wallet type and chain: an index of the executable recipes.",
}
items = []
SKIP_DOCS = {"troubleshooting"}  # served at /blocktools/faq
for f in sorted(glob.glob(f"{C}/docs/*.md")):
    s = os.path.basename(f)[:-3].lower()
    if s in SKIP_DOCS: continue
    t, d = meta(f); d = OVR.get(s, d); items.append(dict(kind="docs", slug=s, file=f"docs/{os.path.basename(f)}", title=t, description=d))
for f in sorted(glob.glob(f"{C}/swapchan/*.md")) + sorted(glob.glob(f"{C}/recipes/*.md")):
    s = os.path.basename(f)[:-3].lower()
    if s == "readme": continue
    t, d = meta(f); t = re.sub(r"^(Recipe|Goal|Input|Chain): ", "", t); t = t[0].upper() + t[1:]
    grp = "swapchan" if "/swapchan/" in f else ("goal" if s.startswith(("goal", "decode", "derive", "offline", "evm")) else "input" if s.startswith("input") else "chain")
    items.append(dict(kind="recipes", slug=s, group=grp, file=os.path.relpath(f, C), title=t, description=d))
out = "// GENERATED by scripts/gen-blocktools.py from content/blocktools. Do not edit.\n"
out += "export type BtItem = { kind: \"docs\" | \"recipes\"; slug: string; group?: string; file: string; title: string; description: string };\n"
out += "export const BT_ITEMS: BtItem[] = " + json.dumps(items, indent=1, ensure_ascii=False) + ";\n"
out += "export const BT_TOOLS: { name: string; desc: string }[] = " + json.dumps(json.load(open(f"{C}/tools.json")), ensure_ascii=False) + ";\n"
open(os.path.join(os.path.dirname(__file__), "..", "src", "lib", "blocktoolsManifest.ts"), "w").write(out)
print(len(items))
